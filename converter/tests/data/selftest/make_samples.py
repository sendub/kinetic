"""Generate the media self-test inputs (docs/plan.md Phase 25, item 25.1).

The committed files in this directory ARE the self-test inputs; the
golden sha256s in converter/media-tools.json are computed from them.
Re-running this script rewrites them, which invalidates the goldens:
null ``selftest.golden`` in media-tools.json and re-run
``.venv/bin/python tools/setup_media_tools.py --pin`` afterwards.

Images come from a fixed-seed numpy generator through Pillow; the video
from ffmpeg's lavfi test sources, single-threaded and bitexact. Any ffmpeg
with libx264 will do (``--ffmpeg PATH``): the bytes it writes are committed
and never regenerated by setup.

    .venv/bin/python converter/tests/data/selftest/make_samples.py
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent


def pixels(height: int, width: int, channels: int, seed: int) -> np.ndarray:
    """A smooth gradient with seeded noise: compressible, not trivial."""
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:height, 0:width]
    base = (x * 255 // max(width - 1, 1) + y * 3)[..., None]
    noise = rng.integers(0, 24, (height, width, channels))
    shift = np.arange(channels) * 40
    return ((base + noise + shift) % 256).astype(np.uint8)


def make_images() -> None:
    rgba = pixels(32, 48, 4, seed=251)
    rgba[..., 3] = np.linspace(40, 255, 48, dtype=np.uint8)[None, :]
    Image.fromarray(rgba, "RGBA").save(HERE / "sample.png", optimize=True)
    rgb = pixels(32, 48, 3, seed=252)
    Image.fromarray(rgb, "RGB").save(HERE / "sample.jpg", quality=90,
                                     subsampling=2, optimize=False,
                                     progressive=False)
    Image.fromarray(pixels(24, 40, 3, seed=253), "RGB").save(
        HERE / "sample.webp", lossless=True, quality=100, method=6)
    frames = [Image.fromarray(pixels(16, 16, 3, seed=s), "RGB").quantize(16)
              for s in (254, 255)]
    frames[0].save(HERE / "sample.gif", save_all=True,
                   append_images=frames[1:], duration=100, loop=0)


def make_video(ffmpeg: str) -> None:
    subprocess.run(
        [ffmpeg, "-nostdin", "-hide_banner", "-v", "error", "-y",
         "-f", "lavfi", "-i", "testsrc=size=64x36:rate=10:duration=1",
         "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=22050:"
         "duration=1",
         "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
         "-c:a", "aac", "-b:a", "32k", "-shortest",
         "-threads", "1", "-fflags", "+bitexact", "-flags:v", "+bitexact",
         "-flags:a", "+bitexact", "-map_metadata", "-1",
         "-movflags", "+faststart", str(HERE / "sample.mp4")],
        check=True)


def make_odd_video(ffmpeg: str) -> None:
    """An odd-sized (63x37) MPEG-4 Part 2 clip: never browser-native, so
    it transcodes, through the even-pad filter."""
    subprocess.run(
        [ffmpeg, "-nostdin", "-hide_banner", "-v", "error", "-y",
         "-f", "lavfi", "-i", "testsrc=size=63x37:rate=10:duration=0.5",
         "-c:v", "mpeg4", "-an", "-threads", "1", "-fflags", "+bitexact",
         "-flags:v", "+bitexact", "-map_metadata", "-1",
         str(HERE / "sample-odd.mp4")],
        check=True)


def main() -> None:
    argp = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    argp.add_argument("--ffmpeg", default="ffmpeg",
                      help="ffmpeg used once to write the sample videos")
    args = argp.parse_args()
    make_images()
    make_video(args.ffmpeg)
    make_odd_video(args.ffmpeg)


if __name__ == "__main__":
    main()
