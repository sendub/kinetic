// Builds the WebKit driver (apps/macos/driver) on first use, into
// .tmp/webkit-driver-build/<hash>/kinetic-webkit-driver, ad-hoc signed. The
// hash covers the Swift sources, the voice helper and the host words table
// the driver embeds and the build flags, so an edit rebuilds and an
// unchanged checkout reuses the last build.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { arch, platform } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
);
// The game app's shared files (tools/build_apps.py MAC_SOURCES) and the
// driver's own; the build adds the generated KineticVoiceEmbedded.swift and
// KineticHostWordsEmbedded.swift.
const SOURCES = [
  join(repoRoot, "apps", "macos", "WebViewSetup.swift"),
  join(repoRoot, "apps", "macos", "VoiceEngine.swift"),
  join(repoRoot, "apps", "macos", "HostWords.swift"),
  join(repoRoot, "apps", "macos", "driver", "main.swift"),
];
const VOICE_DIR = join(repoRoot, "apps", "voice");
const VOICE_LOCK_NAME = "lock-macos-arm64.json";
const EMBEDDED_VOICE_NAME = "KineticVoiceEmbedded.swift";
// The game apps' own words (docs/plan.md Phase 56 item 7), from the
// catalogue by `npm run i18n`.
const HOST_WORDS = join(repoRoot, "apps", "host-words.json");
const EMBEDDED_HOST_WORDS_NAME = "KineticHostWordsEmbedded.swift";
const buildRoot = join(repoRoot, ".tmp", "webkit-driver-build");
const NAME = "kinetic-webkit-driver";
const NEEDS =
  "The WebKit engine needs macOS with a Swift toolchain: Xcode or the Command Line Tools (xcode-select --install).";

/** A missing toolchain or a failed build, said plainly. */
export class DriverBuildError extends Error {}

/** The swiftc flags; the app's minimum macOS, so this build proves it too. */
function flags() {
  const cpu = arch() === "arm64" ? "arm64" : "x86_64";
  return ["-O", "-target", `${cpu}-apple-macos12`];
}

/**
 * KineticVoiceEmbedded.swift: the voice helper's Python files and the Mac
 * lock, base64, by the path each takes under the voice folder's helper/
 * (apps/macos/VoiceEngine.swift writes them there). The same text as
 * tools/build_apps.py's embedded_voice_source (tools/test_build_apps.py
 * compares them), so the driver carries the helper the app carries.
 */
export function embeddedVoiceSource() {
  const pkg = join(VOICE_DIR, "kinetic_voice");
  const names = readdirSync(pkg)
    .filter((name) => name.endsWith(".py"))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const b64 = (file) => readFileSync(file).toString("base64");
  const rows = names
    .map(
      (name) =>
        `        ("kinetic_voice/${name}", "${b64(join(pkg, name))}"),\n`,
    )
    .join("");
  return (
    "// Generated by the build from apps/voice (tools/build_apps.py and\n" +
    "// player/scripts/webkit/build.mjs write the same text); never\n" +
    "// committed. VoiceEngine.swift writes these files into the voice\n" +
    "// folder's helper/.\n" +
    "\n" +
    "enum KineticVoiceEmbedded {\n" +
    "    /// The helper's files, base64, by their path under helper/.\n" +
    "    static let files: [(path: String, base64: String)] = [\n" +
    rows +
    `        ("${VOICE_LOCK_NAME}", "${b64(join(VOICE_DIR, VOICE_LOCK_NAME))}"),\n` +
    "    ]\n" +
    "    /// The lock's path among them.\n" +
    `    static let lockPath = "${VOICE_LOCK_NAME}"\n` +
    "}\n"
  );
}

/**
 * KineticHostWordsEmbedded.swift: apps/host-words.json, base64, which
 * apps/macos/HostWords.swift reads. The same text as tools/build_apps.py's
 * embedded_host_words_source (tools/test_build_apps.py compares them).
 */
export function embeddedHostWordsSource() {
  return (
    "// Generated by the build from apps/host-words.json (tools/build_apps.py\n" +
    "// and player/scripts/webkit/build.mjs write the same text); never\n" +
    "// committed. HostWords.swift reads it.\n" +
    "\n" +
    "enum KineticHostWordsEmbedded {\n" +
    "    /// apps/host-words.json, base64.\n" +
    `    static let base64 = "${readFileSync(HOST_WORDS).toString("base64")}"\n` +
    "}\n"
  );
}

/** Path to a built, signed driver for the current sources (built if need be). */
export function ensureDriver() {
  if (platform() !== "darwin") throw new DriverBuildError(NEEDS);
  const embedded = embeddedVoiceSource();
  const hostWords = embeddedHostWordsSource();
  const hash = createHash("sha256");
  hash.update(flags().join(" "));
  for (const file of SOURCES) {
    hash.update(`\0${relative(repoRoot, file)}\0`);
    hash.update(readFileSync(file));
  }
  hash.update(`\0${EMBEDDED_VOICE_NAME}\0`);
  hash.update(embedded);
  hash.update(`\0${EMBEDDED_HOST_WORDS_NAME}\0`);
  hash.update(hostWords);
  const dir = join(buildRoot, hash.digest("hex").slice(0, 16));
  const binary = join(dir, NAME);
  if (existsSync(binary)) return binary;

  // `xcode-select -p` fails quietly without developer tools, where calling
  // the /usr/bin/swiftc stub would pop up the installer instead.
  const run = (cmd, args) =>
    execFileSync(cmd, args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  try {
    run("xcode-select", ["-p"]);
    run("xcrun", ["--find", "swiftc"]);
  } catch {
    throw new DriverBuildError(NEEDS);
  }
  // Built beside the final folder, then renamed into place, so runs that
  // build at the same moment never see half a binary.
  const partial = `${dir}.partial-${process.pid}`;
  rmSync(partial, { recursive: true, force: true });
  mkdirSync(partial, { recursive: true });
  // Generated beside the build, never in the repo's sources; it stays in
  // the build folder as a record of what went in.
  const embeddedFile = join(partial, EMBEDDED_VOICE_NAME);
  writeFileSync(embeddedFile, embedded);
  const hostWordsFile = join(partial, EMBEDDED_HOST_WORDS_NAME);
  writeFileSync(hostWordsFile, hostWords);
  try {
    // Through xcrun, which hands swiftc the macOS SDK.
    run("xcrun", [
      "--sdk",
      "macosx",
      "swiftc",
      ...flags(),
      "-module-cache-path",
      join(buildRoot, "module-cache"),
      "-o",
      join(partial, NAME),
      ...SOURCES,
      embeddedFile,
      hostWordsFile,
    ]);
    run("codesign", ["--force", "--sign", "-", join(partial, NAME)]);
  } catch (error) {
    rmSync(partial, { recursive: true, force: true });
    throw new DriverBuildError(
      `Building the WebKit driver failed:\n${error.stderr || error.message}`,
    );
  }
  try {
    renameSync(partial, dir);
  } catch {
    // Another run finished the same build first; use that one.
    rmSync(partial, { recursive: true, force: true });
  }
  return binary;
}
